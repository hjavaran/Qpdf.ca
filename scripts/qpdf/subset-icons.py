#!/usr/bin/env python3
"""Build a small Phosphor icon font for Qpdf's own pages.

The full Phosphor web font is ~145 KB; Qpdf's homepage, directory and content
pages use about 100 icons. This script subsets the font to exactly those icons
and writes:

  src/css/fonts/qpdf-icons.woff2   (subset font, committed)
  src/css/icons-site.css           (@font-face + .ph-* rules, committed)

Tool pages keep using the full font through styles.css, because upstream tool
code creates icons dynamically.

Run after adding an icon to src/data/tools.mjs or to a site page:
    pip install fonttools brotli
    python3 scripts/qpdf/subset-icons.py
scripts/qpdf/prebuild.mjs fails the build if an icon is missing from the subset.
"""
import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
PH = ROOT / "node_modules/@phosphor-icons/web/src/regular"
SOURCES = [
    ROOT / "src/data/tools.mjs",
    *ROOT.glob("*.html"),
    ROOT / "guides/index.html",
    *(ROOT / "src/partials").glob("*.html"),
    *(ROOT / "src/templates").glob("*.html"),
    *(ROOT / "src/js/qpdf").glob("*.ts"),
]
# Icons always kept (used by future content or dynamic code).
EXTRA = {"ph-magnifying-glass", "ph-lock-simple", "ph-shield-check", "ph-wifi-slash", "ph-arrow-right"}

css = (PH / "style.css").read_text()
codepoints = dict(re.findall(r'\.ph\.(ph-[a-z0-9-]+):before \{\s*content: "\\([0-9a-f]+)";', css))

used = set(EXTRA)
for src in SOURCES:
    if src.exists():
        used.update(m for m in re.findall(r"\bph-[a-z0-9-]+\b", src.read_text()) if m in codepoints)
used = sorted(used)
missing = [u for u in used if u not in codepoints]
if missing:
    raise SystemExit(f"Unknown Phosphor icons: {missing}")

out_font = ROOT / "src/css/fonts/qpdf-icons.woff2"
out_font.parent.mkdir(parents=True, exist_ok=True)
font = TTFont(PH / "Phosphor.ttf")
opts = subset.Options()
opts.flavor = "woff2"
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(codepoints[u], 16) for u in used])
sub.subset(font)
font.flavor = "woff2"
font.save(out_font)

rules = "\n".join(f'.ph.{u}::before {{ content: "\\{codepoints[u]}"; }}' for u in used)
(ROOT / "src/css/icons-site.css").write_text(
    "/* Generated by scripts/qpdf/subset-icons.py — do not edit by hand.\n"
    "   Phosphor Icons (MIT), subset to the icons used on Qpdf's own pages. */\n"
    "@font-face {\n  font-family: 'Qpdf Icons';\n  src: url('./fonts/qpdf-icons.woff2') format('woff2');\n"
    "  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}\n"
    ".ph {\n  font-family: 'Qpdf Icons' !important;\n  font-style: normal;\n  font-weight: normal;\n"
    "  line-height: 1;\n  speak: never;\n  -webkit-font-smoothing: antialiased;\n  -moz-osx-font-smoothing: grayscale;\n}\n"
    + rules + "\n"
)
print(f"subset-icons: {len(used)} icons, {out_font.stat().st_size:,} bytes → {out_font.relative_to(ROOT)}")
