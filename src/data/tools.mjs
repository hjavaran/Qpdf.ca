// Used at build time to render: the homepage/tool directory, each tool's
// <head> metadata, its landing-page content, related-tool links, the site
// index, the sitemap and the offline-readiness manifest.
//
// Fields
//   id        Source page name: src/pages/<id>.html (upstream BentoPDF name)
//   slug      Public URL path segment: https://qpdf.ca/<slug>/
//   name      Display name (also the on-page H1 for most tools)
//   cat       Category key (see CATEGORIES)
//   icon      Phosphor icon class
//   short     One-line card description
//   title     <title> (keep under ~65 characters)
//   desc      Meta description (keep under ~160 characters)
//   intro     Short original explanation shown under the tool
//   steps     How-to steps
//   notes     Limitations, warnings and tips
//   related   Related tool ids
//   kw        Extra search keywords for the directory filter
//   engine    Processing engine. Drives the offline indicator and
//             what is cached for offline use:
//               core        bundled pdf-lib / PDF.js / qpdf / PDFium / Hyper Compress
//               cpdf        CoherentPDF (self-hosted, ~9 MB)
//               pymupdf     PyMuPDF on Pyodide (self-hosted, ~54 MB)
//               gs          Ghostscript (self-hosted, ~15 MB)
//               tesseract   Tesseract OCR (self-hosted, core + language data)
//               vips        wasm-vips (bundled)
//               libreoffice LibreOffice (needs the R2 asset host, see docs)
//   needs     'libreoffice' if the tool needs the external LibreOffice assets
//   disabled  true to exclude the tool from the build entirely
//   popular   true to show in "Popular tools"
